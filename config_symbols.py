# ★ 为什么不用天勤的 quote.margin（实测结论，别改回去）：
#   1) 回测里它是**静态快照**：PVC 价格 3 个月涨 39%（7628→10600），margin 一动不动；
#   2) 老合约返回的是**占位值**：DCE.v1605 与 DCE.v2005 的 margin 竟然都是 1638.75；
#   3) 真实交易所保证金 = 结算价 × 乘数 × 费率，**本来就是随价格浮动的**。
#   ⇒ 真要「动态」，动态的是**价格**这一项，不是那个字段。
#
# 取值依据：用天勤当时可得的真实具体合约反推  margin ÷ (价格 × 乘数)，
#          两个时点（2025-01 六个品种 / 2026-03 十二个品种）各测一次，**取较大值**。
#          取大 = 每手保证金算得高 = 上限压得紧 = 偏保守，方向安全。
#          ⚠️ 交易所会随行情/临近交割上调保证金（实测甲醇 6.09% ↔ 9.59%），
#             所以本表是「典型偏保守值」，不是逐日精确值 —— 它是**保护阀**，
#             不是收益来源，不必也不应据此调参（规则 2）。
