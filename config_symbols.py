# ===========================================================
# 2026-09-28 新增。用途：引擎不再需要外部传「每手保证金」这个静态数字，
# 而是每根 K 线用  `当时价格 × 合约乘数 × 本表费率`  现算 ⇒ 手数上限随价格浮动。
