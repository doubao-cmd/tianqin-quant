# 手续费：固定元/手 + 成交额比例（2026-10-18 新增）
# ===========================================================
# 为什么加：工作台卡C 从 55 品种池里选品种（`策略/06_MA13超短线/工作台/`），
#   选中的品种必须能在这里解析出 乘数/tick/成本，否则 `get()` 直接 SystemExit。
