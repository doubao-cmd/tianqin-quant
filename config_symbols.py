def get(key):
    """按缩写取品种信息，写错会给出友好提示"""
    key = key.upper()
    if key not in SYMBOLS:
        raise SystemExit(f"品种代号写错了：{key}\n可用：{', '.join(SYMBOLS.keys())}")
    return SYMBOLS[key]


