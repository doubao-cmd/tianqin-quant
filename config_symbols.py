# ⇒ 新增 `COMM_RATE`（单边比例，占成交额）+ `comm_per_hand(key, price)`：
#   有比例就用「比例×当期价格×乘数」现算；否则回退 COST 常数。
#   ★ 已有 12 个品种的 COST/MARGIN_RATE **一个都不改**（值经实盘/回测核验，
#     改动会让历史结论失真）。新表只 `setdefault` 补齐缺的品种。
