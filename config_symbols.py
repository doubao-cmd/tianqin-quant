def comm_per_hand(key, price=None):
    """单边每手手续费（元）。

    - 比例品种（在 COMM_RATE 里）：rate × 当期价格 × 乘数
    - 其余品种：直接返回 COST 常数（与旧口径逐字一致）
    - price 缺失/非正时，比例品种回退 COST 快照（宁可粗一点，不要 0 成本）
    """
    k = str(key).upper()
    rate = float(COMM_RATE.get(k, 0.0) or 0.0)
    base = float(COST.get(k, 0.0) or 0.0)
    if rate <= 0:
        return base
    try:
        p = float(price)
        mult = float(SYMBOLS[k][2])
    except Exception:
        return base
    if not (p == p and p > 0 and mult > 0):
        return base
    return rate * p * mult


