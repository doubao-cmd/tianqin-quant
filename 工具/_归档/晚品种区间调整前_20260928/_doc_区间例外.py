# -*- coding: utf-8 -*-
"""把「晚上市品种练习区间单独后移」这件事写进各处文档。

2026-09-28 用户拍板：纯碱 / 苯乙烯 / 生猪 上市晚（2019-12-05 / 2019-09-25 / 2021-01-07），
2016-2019 一根行情都没有 ⇒ 这仨的练习区间单独后移为 2020-01-01 ~ 2022-12-31，
验证集顺延为 2023-01-01 ~ 2024-12-31，期末考不变；其余 9 个品种不动。

涉及文件（全部 LF 行尾，改完保持 LF）：
    README.md（隐藏）
    目录地图.md（隐藏）
    策略/01_双均线/_档案.md ... 策略/05_摆动线/_档案.md
    策略/_说明.md

用法：
    python _doc_区间例外.py          # 干跑
    python _doc_区间例外.py --go     # 真改
"""
import os
import shutil
import sys

本目录 = os.path.dirname(os.path.abspath(__file__))
_ROOT = 本目录
while _ROOT != os.path.dirname(_ROOT) and not os.path.isdir(os.path.join(_ROOT, "lib")):
    _ROOT = os.path.dirname(_ROOT)

旧_全局行 = ("> ⚠️ 2016 年只有 **9 个品种**有数据（纯碱/苯乙烯/生猪未上市或刚上市）；\n"
             "> ⚠️ 期末考**不干净**：2025-03~09 曾被 01 烧掉、2026-03~09 曾是样本内（用户知情接受）。\n")
新_全局行 = ("> ⚠️ **例外（2026-09-28 用户拍板）**：纯碱 / 苯乙烯 / 生猪 **上市晚**（2019-12-05 / 2019-09-25 / 2021-01-07），\n"
             "> 2016-2019 **一根行情都没有** ⇒ 这仨的练习区间**单独后移**为 **2020-01-01 ~ 2022-12-31**、\n"
             "> 验证集顺延为 **2023-01-01 ~ 2024-12-31**、期末考不变；其余 9 个品种不动。\n"
             "> **这仨与其余 9 个品种样本期不同期，横向比较/组合时要留意。**\n"
             "> ⚠️ 期末考**不干净**：2025-03~09 曾被 01 烧掉、2026-03~09 曾是样本内（用户知情接受）。\n")

旧_档案行 = "> 新区间 = **样本内 2016-01-01 ~ 2019-12-31 ｜ 验证集 2020-01-01 ~ 2024-12-31 ｜ 期末考试 2025-01-01 ~ 2026-09-30**。\n"
新_档案行 = (旧_档案行 +
             "> ★ **例外（2026-09-28 用户拍板）**：纯碱 / 苯乙烯 / 生猪 上市晚（2019-12-05 / 2019-09-25 / 2021-01-07），\n"
             "> 2016-2019 无行情 ⇒ 这仨本策略的练习区间单独后移为 **2020-01-01 ~ 2022-12-31**、验证集 **2023-01-01 ~ 2024-12-31**，期末考不变。\n")

旧_说明表 = ("| **样本内（练习）** | **2016-01-01 ~ 2019-12-31** | 4 年 | 开发用，**可反复跑** |\n"
             "| **验证集** | **2020-01-01 ~ 2024-12-31** | 5 年 | 结构选择，**可跑有限几次** |\n")
新_说明表 = (旧_说明表 +
             "| ↳ **例外：纯碱/苯乙烯/生猪** | 练习 **2020-01-01 ~ 2022-12-31**｜验证 **2023-01-01 ~ 2024-12-31** | 3 年 / 2 年 | "
             "上市晚（2019-12-05 / 2019-09-25 / 2021-01-07），2016-2019 无行情 ⇒ 区间单独后移，**不与其余 9 品种同步**（2026-09-28 用户拍板） |\n")

任务 = [
    ("README.md", 旧_全局行, 新_全局行),
    ("目录地图.md", 旧_全局行, 新_全局行),
    ("策略/_说明.md", 旧_说明表, 新_说明表),
]
for s in ("01_双均线", "02_均线排列", "03_均值回归", "04_通道突破", "05_摆动线"):
    任务.append((os.path.join("策略", s, "_档案.md"), 旧_档案行, 新_档案行))


def 读(p):
    with open(p, encoding="utf-8", newline="") as f:
        return f.read()


def 写(p, t):
    with open(p, "w", encoding="utf-8", newline="") as f:
        f.write(t)


def main():
    真改 = "--go" in sys.argv
    print("=" * 74)
    print("  文档：写入「晚上市品种区间例外」  " + ("【真改】" if 真改 else "【干跑】"))
    print("=" * 74)
    问题 = []
    待改 = []
    for 相对, 旧, 新 in 任务:
        p = os.path.join(_ROOT, 相对)
        if not os.path.exists(p):
            问题.append("文件不存在：%s" % 相对)
            continue
        t = 读(p)
        if t.count(旧) != 1:
            问题.append("%s：旧文本命中 %d 次（应为 1）" % (相对, t.count(旧)))
            continue
        b = open(p, "rb").read()
        if b.count(b"\r\n"):
            问题.append("%s：含 CRLF，本应 LF" % 相对)
            continue
        待改.append((相对, p, 旧, 新))
    if 问题:
        for q in 问题:
            print("  ✗ " + q)
        return 1

    for 相对, p, 旧, 新 in 待改:
        if 真改:
            备份 = os.path.join(本目录, 相对)
            os.makedirs(os.path.dirname(备份), exist_ok=True)
            shutil.copy2(p, 备份)
            t = 读(p).replace(旧, 新, 1)
            写(p, t)
            b = open(p, "rb").read()
            if b.count(b"\r\n"):
                print("  ✗ %s 写回后变成 CRLF" % 相对)
                return 1
        print("  [%s] %s" % ("改" if 真改 else "将改", 相对))
    print("-" * 74)
    print("  %s %d 个文件" % ("已改" if 真改 else "待改", len(待改)))
    if not 真改:
        print("  这是干跑。要真改请加 --go")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
