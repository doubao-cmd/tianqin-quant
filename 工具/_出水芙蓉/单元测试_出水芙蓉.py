# -*- coding: utf-8 -*-
"""出水芙蓉核心纯函数的合成数据单元测试（不连网）"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np  # noqa: E402
import 核心 as K  # noqa: E402

失败 = []


def 检查(名, 条件):
    print(("  ✅ " if 条件 else "  ❌ ") + 名)
    if not 条件:
        失败.append(名)


print("【1】多头信号（出水芙蓉 5 条件逐条 toggled）")
up = 104.0
检查("全部满足 → True", K.是多头信号(100, 110, 1000, up, 5.0, 300.0) is True)
检查("破①开盘已在群上方 → False", K.是多头信号(105, 110, 1000, up, 5.0, 300.0) is False)
检查("破②收盘未站上群 → False", K.是多头信号(100, 103, 1000, up, 5.0, 300.0) is False)
检查("破③非阳线 → False", K.是多头信号(110, 100, 1000, up, 5.0, 300.0) is False)
检查("破④实体不足(6<7.5) → False", K.是多头信号(100, 106, 1000, up, 5.0, 300.0) is False)
检查("破⑤量不足(800<900) → False", K.是多头信号(100, 110, 800, up, 5.0, 300.0) is False)
检查("NaN(如均线未热身) → False", K.是多头信号(100, 110, 1000, np.nan, 5.0, 300.0) is False)

print("【2】空头信号（断头铡刀镜像）")
dn = 96.0
检查("全部满足 → True", K.是空头信号(100, 90, 1000, dn, 5.0, 300.0) is True)
检查("破镜像①开盘已在群下方 → False", K.是空头信号(95, 90, 1000, dn, 5.0, 300.0) is False)
检查("破镜像②收盘未跌破群 → False", K.是空头信号(100, 97, 1000, dn, 5.0, 300.0) is False)

print("【3】均线群上下沿 + NaN 传播")
a, b = K.均线群上下沿(102.0, 103.0, 104.0)
检查("上沿=104 下沿=102", a == 104.0 and b == 102.0)
a2, _ = K.均线群上下沿(102.0, 103.0, np.nan)
检查("任一 NaN → 上沿 NaN（信号层判 False）", not np.isfinite(a2))

print("【4】原始止损位置")
检查("多=芙蓉低−1跳", K.原始止损(99.0, 1.0, 1) == 98.0)
检查("空=芙蓉高+1跳", K.原始止损(111.0, 1.0, -1) == 112.0)

print("【5】止损夹紧（10-08 铁律）")
检查("正常：多止损98 < 入场110 → 原样", K.夹紧止损(98.0, 110.0, 5.0, 1.0, 1) == 98.0)
检查("贴身：多止损109.5 ≥ 110−1 → 收紧到 110−2×5=100",
     K.夹紧止损(109.5, 110.0, 5.0, 1.0, 1) == 100.0)
检查("有利侧：多止损111 > 入场 → 收紧", K.夹紧止损(111.0, 110.0, 5.0, 1.0, 1) == 100.0)
检查("正常：空止损112 > 入场90+1 → 原样", K.夹紧止损(112.0, 90.0, 5.0, 1.0, -1) == 112.0)
检查("有利侧：空止损89 < 入场 → 收紧到 90+10=100",
     K.夹紧止损(89.0, 90.0, 5.0, 1.0, -1) == 100.0)

print("【6】止损成交价（GAP_FILL）")
检查("多：跳空低开 97 → 按开盘", K.止损成交多(98.0, 97.0) == 97.0)
检查("多：未跳空 99 → 按线", K.止损成交多(98.0, 99.0) == 98.0)
检查("空：跳空高开 115 → 按开盘", K.止损成交空(112.0, 115.0) == 115.0)
检查("空：未跳空 → 按线", K.止损成交空(112.0, 110.0) == 112.0)

print("【7】前高止盈成交（B1：限价−1跳）")
检查("多：盘中触及(开118<X=120) → 120−1=119", K.止盈成交多(120.0, 118.0, 1.0) == 119.0)
检查("多：开盘已越过(开125) → 125−1=124", K.止盈成交多(120.0, 125.0, 1.0) == 124.0)
检查("空：盘中触及 → 80+1=81", K.止盈成交空(80.0, 82.0, 1.0) == 81.0)
检查("空：开盘已越过 → 78+1=79", K.止盈成交空(80.0, 78.0, 1.0) == 79.0)

print("【8】手数（止损距离定风险，夹[1,8]，锁20万×1%）")
检查("距11点×乘数10=单手亏110 → 2000/110=18 → 封顶8",
     K.目标手数(3407.0, 3396.0, 10, 1.0) == 8)
检查("距100点×10=1000 → 2 手", K.目标手数(3407.0, 3307.0, 10, 1.0) == 2)
检查("距=0 → 最小", K.目标手数(3407.0, 3407.0, 10, 1.0) == 1)
检查("NaN → 最小", K.目标手数(np.nan, 3396.0, 10, 1.0) == 1)

print("【9】结构不变量：多单止损成交价必在入场价不利侧")
ok = True
for ep in (110.0, 3407.0, 5548.0):
    st = K.夹紧止损(K.原始止损(ep - 12.0, 1.0, 1), ep, 5.0, 1.0, 1)
    for op_ in (st - 3.0, st, ep + 5.0):     # 跳空/未跳空/高开
        px = K.止损成交多(st, op_)
        if not (px < ep):
            ok = False
检查("随机组合下 全部 exit < entry", ok)

print()
if 失败:
    print("❌ 失败 %d 项: %s" % (len(失败), 失败))
    sys.exit(1)
print("✅ 全部通过")
