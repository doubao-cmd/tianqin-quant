# -*- coding: utf-8 -*-
"""
通道突破（唐奇安 / 海龟原型）—— 纯逻辑层
==========================================================
只做两件事：算信号、算手数。不含品种、不含路径、不含账号、不扣成本。

【一句话逻辑】
  收盘价突破「前 N 根」的最高价 -> 做多；
  跌破   「前 N 根」的最低价     -> 做空；
  持有中反向跌破 / 升破出场轨道 -> 平仓离场（**不反手**）；
  亏损达到止损宽度              -> 止损。

【为什么是它】
  用户路线（2026-09-27）：不靠消息面、只用技术面；走趋势跟踪（低胜率 + 大盈亏比）。
  趋势跟踪唯一不需要预测能力的正期望来源就是「结构性盈亏比」——
  亏的时候亏小（止损封顶），赚的时候让利润跑（反向破位才走）。
  通道突破是这个结构最朴素、参数最少的一种写法（一个窗口 + 一个止损宽度）。

⚠️ 与 lib/engine.channel_signal 的关系
--------------------------------------
本文件是 `lib/engine.py::channel_signal` 的**等价搬运**（离线逐根版），
引擎里的原函数**保持不动**，既有 04 的历史回测继续走旧路径。
本文件不引入任何新参数、不改任何数字 —— 只搬逻辑。

【硬性规则】（用户 2026-09-16 下达，不可违反）
  1. 禁未来函数：只用已收盘K线，下单在下一根开盘；禁用重绘指标(ZigZag)
  2. 先有交易逻辑再写代码：不叠加过滤、不遍历参数择优、避免过拟合
  3. 样本内外分离：样本外只用于最终验证，看过即污染须换区间
  4. 条件简洁，每次只改动一处逻辑

【规则：本文件不得出现的字符/词】
  品种名（甲醇/PVC/纯碱/螺纹钢/豆粕）、合约代码（CZCE./DCE./SHFE.）、
  任何绝对路径、任何账号 —— 出现即为分层违规。
"""

# ============================================================
# 参数（一次设定，固定；不扫描择优）
# ============================================================
参数 = {
    # ---- 信号 ----
    "入场窗口": 60,          # 前 60 根极值。30min 下 ≈ 5 个交易日（对应「持有几天」）
    "出场窗口": 60,          # 反向破位离场。与入场同宽 = 破位即走

    # ---- 止损 ----
    "ATR_PERIOD": 20,        # ATR 周期（止损宽度用；经典值，不扫描）
    # ★ 止损宽度 = 止损_日ATR倍数 × √每日根数 × ATR(ATR_PERIOD)
    #   为什么带 √每日根数：ATR 是「**一根** bar 的平均真实波幅」。
    #   30min 的 ATR(20) 量的是单根 30min 的波幅（约 0.6%），不是「一天的波幅」。
    #   一天的波幅要把当日各根合起来看 —— 独立同分布下 ≈ 单根 × √N。
    #   N = 每日根数（30min 下 12 根）⇒ 折算系数 √12 ≈ 3.46。
    #   ⚠️ 2026-09-27 实测事故：漏掉这个折算，止损窄了 3.5 倍，
    #      胜率 29.2% -> 8.2%，几乎每笔被扫。详见 新起点/输出/期望拆解_MA_30min.md 第七节。
    #   这是**设计选择**（持有几天 ⇒ 用日线尺子量），不是择优。
    "止损_日ATR倍数": 1.0,
    "每日根数": 12,          # ★ 周期属性：30min 下 12 根/日。组合层按周期覆盖它
}


# ============================================================
# 信号（等价于 engine.channel_signal 的状态机）
# ============================================================
def 通道(k线表, n, 高列="high", 低列="low"):
    """前 n 根（**不含当前根**）的最高 / 最低 —— 一律 shift(1)。

    ★ shift(1) 不能省：少了它就把「当前这根」的 high/low 算进轨道，
      等于拿本根的极值判断本根 —— 未来函数（规则 1）。
    """
    h, l = k线表[高列], k线表[低列]
    return h.rolling(n).max().shift(1), l.rolling(n).min().shift(1)


def 算信号(k线表, 参数=None, 初仓=0):
    """逐根生成目标仓位序列（1 多 / 0 空 / -1 空头）。

    ⚠️ k线表 必须只含**已收盘** K 线。第 i 根产生的信号，由 engine 在第 i+1 根
    开盘价成交 —— 本函数不看 i+1 及以后，无未来函数。

    状态机（与 engine.channel_signal 逐字对应）：
        持多：close < 出场下轨 -> 0（平多离场）
        持空：close > 出场上轨 -> 0（平空离场）
        空仓：close > 入场上轨 -> +1（做多）
              close < 入场下轨 -> -1（做空）
        其余：维持当前方向
      NaN（预热不足 / 非法价）一律**维持现状** —— 判正不判负。

    ★ 为什么出场即空仓、不反手：入场与出场是两个独立参数、对应两条独立规则
      （进场规则 / 离场规则），这正是海龟原版的结构。跌破出场轨道就反手的话，
      出场轨道实际变成「反手轨道」，两个参数的分工被抹掉，事后说不清是哪条在起作用。
    """
    p = 参数 if 参数 else globals()["参数"]
    n1, n2 = int(p["入场窗口"]), int(p["出场窗口"])
    en_up, en_dn = 通道(k线表, n1)
    ex_up, ex_dn = 通道(k线表, n2)
    close = k线表["close"]

    out = []
    pos = 初仓                              # 当前仓位方向（±1 / 0）
    for i in range(len(k线表)):
        c = close.iloc[i]
        if not (c == c and c > 0):          # NaN / 非法价 -> 什么都不做
            out.append(pos)
            continue
        if pos > 0:
            e = ex_dn.iloc[i]
            if e == e and c < e:
                pos = 0                     # 平多
        elif pos < 0:
            e = ex_up.iloc[i]
            if e == e and c > e:
                pos = 0                     # 平空
        else:
            u, d = en_up.iloc[i], en_dn.iloc[i]
            if u == u and d == d:           # 两条入场轨道都有效才允许开仓
                if c > u:
                    pos = 1
                elif c < d:
                    pos = -1
        out.append(pos)
    return out


def 止损宽度(atr, 参数=None):
    """把 ATR(信号周期) 折算成「止损宽度（价格）」。

        止损宽度 = 止损_日ATR倍数 × √每日根数 × ATR

    atr 为 None / NaN / <= 0 时返回 0（调用方据此判「本根没法开仓」）。
    """
    p = 参数 if 参数 else globals()["参数"]
    try:
        a = float(atr)
    except Exception:
        return 0.0
    if not (a == a) or a <= 0:
        return 0.0
    return float(p["止损_日ATR倍数"]) * (float(p["每日根数"]) ** 0.5) * a


# ============================================================
# 手数（波动率预算）
# ============================================================
def 算手数(权益, atr, 乘数, 参数=None, 手数下限=1, 手数上限=0):
    """波动率预算：手数 = 权益 × RISK_PCT% ÷ 止损宽度 ÷ 乘数。

    ⚠️ 用波动率定手数是**合法的**风险控制；
       用波动率决定「要不要交易」是行情过滤，属违规 —— 本函数只管手数。

    手数上限 0 = 不夹（让风险预算说话）。下限 1 = 只保证「不能开 0 手」。
    atr 无效时返回下限（保守，不放大风险）。
    """
    p = 参数 if 参数 else globals()["参数"]
    risk_pct = float(p.get("RISK_PCT", 0.0) or 0.0)
    if risk_pct <= 0:
        return int(手数下限)
    宽 = 止损宽度(atr, p)
    try:
        unit = 宽 * float(乘数)
        if not (unit > 0):
            return int(手数下限)
        hand = int(round(float(权益) * risk_pct / 100.0 / unit))
    except Exception:
        return int(手数下限)
    if 手数上限 and 手数上限 > 0:
        hand = min(int(手数上限), hand)
    return max(int(手数下限), hand)


