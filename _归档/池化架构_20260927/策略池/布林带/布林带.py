# ============================================================
# 参数（v4 定格口径，一次设定，不扫描）
# ============================================================
参数 = {
    "BOLL_N": 20,           # 中轨均线周期（标准 20，不扫描）
    "BOLL_K": 2.0,          # 上下轨 = 中轨 ± K 倍标准差（标准 2.0，不扫描）
    "ATR_PERIOD": 14,       # ATR 周期（止损线与手数共用同一把尺子）
    "ATR_STOP_MULT": 1.0,   # v3：1×ATR 固定止损（锚=信号根收盘价，不移动）
    "TIME_STOP_BARS": 20,   # v2：持仓满 20 根未出场 -> 假设失效离场
    "RISK_PCT": 0.30,       # v4：单笔风险 = 基数 × 0.30%
    "RISK_EQUITY": 400000,  # v4：基数 40 万（与回测 INIT_BALANCE 同口径）
    "HAND_MIN": 8,          # 下限 = 合约最小限价开仓手数（消除静默拒单）
    "HAND_MAX": 25,         # 上限 = 纯保护阀（历史最大 24.3 手，样本内零截断）
    "EXIT_OFF": 0.25,       # v1 超调出场：中轨另一侧 0.25×(upper-lower) = 0.5×半带宽
}


# ============================================================
# 指标（纯计算，只用已收盘序列）
# ============================================================
def 布林带(收盘序列, n=None, k=None, 参数_=None):
    """标准布林带：中轨 = MA(n)，上/下轨 = 中轨 ± k×总体标准差。

    与 lib.engine._boll 口径一致：pandas rolling 默认 ddof=0（总体标准差）。
    返回 (mid, upper, lower)，前 n-1 个为 NaN。
    """
    import pandas as pd
    p = 参数_ or 参数
    n = n or p["BOLL_N"]
    k = k if k is not None else p["BOLL_K"]
    mid = pd.Series(收盘序列).rolling(n).mean()
    sd = pd.Series(收盘序列).rolling(n).std()      # ddof=0，与引擎一致
    return mid, mid + k * sd, mid - k * sd


# ============================================================
# 信号（等价于 engine.boll_decision 的状态机）
# ============================================================
def 算信号(k线表, 参数=None, 初仓=0):
    """逐根生成目标仓位序列（1 多 / 0 空 / -1 空头）。

    ⚠️ k线表 必须只含**已收盘** K 线。第 i 根产生的信号，由 engine 在第 i+1 根
    开盘价成交 —— 本函数不看 i+1 及以后，无未来函数。

    状态机（与 engine.boll_decision 逐字对应）：
        空仓：close <= 下轨 -> +1 开多；close >= 上轨 -> -1 开空
        持多：close >= mid + 0.25×(upper-lower) -> 0 平多（v1 超调出场）
        持空：close <= mid - 0.25×(upper-lower) -> 0 平空
      NaN 时比较恒 False -> 保持不动（与引擎 nan 行为一致）。
    """
    p = 参数 if 参数 else globals()["参数"]
    close = k线表["close"]
    mid, up, lo = 布林带(close, 参数_=p)
    ex = p["EXIT_OFF"]                    # 0.25 ⇒ 0.5×半带宽

    out = []
    pos = 初仓                             # 当前仓位（手数方向，±1）
    for i in range(len(k线表)):
        m, u, l, c = mid.iloc[i], up.iloc[i], lo.iloc[i], close.iloc[i]
        if pos > 0:
            if c >= m + (u - l) * ex:
                pos = 0                    # 平多
        elif pos < 0:
            if c <= m - (u - l) * ex:
                pos = 0                    # 平空
        else:
            if c <= l:
                pos = 1                    # 开多
            elif c >= u:
                pos = -1                   # 开空
        out.append(pos)
    return out


# ============================================================
# 手数（波动率预算）
# ============================================================
def 算手数(权益, atr, 乘数, 参数=None):
    """波动率预算：手数 = 权益 × RISK_PCT ÷ (ATR_STOP_MULT × ATR × 乘数)，夹 [min, max]。

    ⚠️ 用波动率定手数是**合法的**风险控制；
       用波动率决定「要不要交易」是行情过滤，属违规 —— 本函数只管手数。

    atr 为 None / nan / 0 时返回 HAND_MIN（保守，不放大风险）。
    """
    p = 参数 if 参数 else globals()["参数"]
    try:
        risk = float(权益) * float(p["RISK_PCT"]) / 100.0
        unit = float(p["ATR_STOP_MULT"]) * float(atr) * float(乘数)
        if not (unit > 0):
            return int(p["HAND_MIN"])
        hand = int(round(risk / unit))
    except Exception:
        return int(p["HAND_MIN"])
    return max(int(p["HAND_MIN"]), min(int(p["HAND_MAX"]), hand))


