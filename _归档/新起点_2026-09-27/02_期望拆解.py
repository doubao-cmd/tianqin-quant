# -*- coding: utf-8 -*-
"""02 期望拆解 —— 让「期望」这个数字当场算给你看
=================================================
逻辑一句话：
  价格突破前 5 个交易日的最高价 -> 做多；跌破最低价 -> 做空；
  反向破了就平；亏到 1×ATR 就止损。

参数（事先定死，跑完不改，不管结果好坏都不回头调）：
  突破窗口   60 根 30 分钟  ≈ 5 个交易日（约 12 根/日）
  止损       1 × 日线 ATR(20)  ← 按交易日聚合成日线后算，用【昨天收盘后】的值
  手数       固定 1 手 —— 手数/仓位管理是第 5 步的事，这一轮不掺进来
  不反手     平仓后必须等下一个新信号，才再开仓

★ 关于止损的周期换算（第一次跑错的地方）：
  ATR 是「一根 bar 的平均真实波幅」。
  ATR(60根30分钟) 是【单根 30 分钟 bar】的波幅（约 0.6%），不是「5 天的波幅」。
  拿它当持有几天的止损，宽度窄了约 sqrt(12)≈3.5 倍 => 几乎每笔都被扫掉。
  正确做法：在 30 分钟数据里【按交易日聚合成日线】，再算日线 ATR(20)。
  本脚本同时保留错误版（止损列=atr30）作为对照，见报告第七节。

防未来函数：
  信号用【已收盘】bar 的收盘价判断 -> 【下一根 bar 的开盘价】成交
  止损用的日线 ATR 取【前一交易日】，不用当天（当天还没收盘）
  止损是事先挂好的价格，盘中触及即成交；若开盘跳空穿越，按开盘价成交（更差）

成本（甲醇 MA）：
  一跳 = 1 元/吨 × 10 吨/手 = 10 元/手
  滑点 2 跳/边 × 2 边 = 4 跳 = 40 元/手 ；手续费 往返约 8 元/手
  合计 48 元/手 每次交易

用法：python 新起点/02_期望拆解.py
输出：新起点/输出/期望拆解_MA_30min.md
      新起点/输出/交易明细_MA_30min.csv
"""
import os

import numpy as np
import pandas as pd

_HERE = os.path.dirname(os.path.abspath(__file__))
_DATA = os.path.join(_HERE, '数据', 'MA_30min.csv')
_OUT = os.path.join(_HERE, '输出')

窗口 = 60
日ATR窗口 = 20
止损倍数 = 1.0
手数 = 1
乘数 = 10
每跳 = 10
滑点跳 = 2
手续费往返 = 8
成本 = 滑点跳 * 2 * 每跳 + 手续费往返


def 算ATR(高, 低, 收, n):
    前收 = 收.shift()
    真波 = pd.concat([高 - 低, (高 - 前收).abs(), (低 - 前收).abs()], axis=1).max(axis=1)
    return 真波.rolling(n).mean()


def 备数据():
    df = pd.read_csv(_DATA)
    df['时间'] = pd.to_datetime(df['时间'])
    df['日期'] = df['时间'].dt.date

    df['atr30'] = 算ATR(df['高'], df['低'], df['收'], 窗口)

    日 = df.groupby('日期').agg(高=('高', 'max'), 低=('低', 'min'), 收=('收', 'last')).reset_index()
    日['atr'] = 算ATR(日['高'], 日['低'], 日['收'], 日ATR窗口)
    日['atr_昨'] = 日['atr'].shift(1)
    df = df.merge(日[['日期', 'atr_昨']], on='日期', how='left')
    return df


def 回测(df, 止损列):
    交易 = []
    i = 窗口
    while i < len(df) - 2:
        bar = df.iloc[i]
        前高 = df['高'].iloc[i - 窗口:i].max()
        前低 = df['低'].iloc[i - 窗口:i].min()

        方向 = 0
        if bar['收'] > 前高:
            方向 = 1
        elif bar['收'] < 前低:
            方向 = -1

        幅度 = bar[止损列]
        if 方向 == 0 or pd.isna(幅度) or 幅度 <= 0:
            i += 1
            continue

        j = i + 1
        开仓价 = df['开'].iloc[j]
        atr = 幅度 * 止损倍数
        止损价 = 开仓价 - atr if 方向 > 0 else 开仓价 + atr

        k = j
        平仓价, 原因 = None, None
        while k < len(df):
            b = df.iloc[k]
            if 方向 > 0 and b['低'] <= 止损价:
                平仓价, 原因 = min(止损价, b['开']), '止损'
                break
            if 方向 < 0 and b['高'] >= 止损价:
                平仓价, 原因 = max(止损价, b['开']), '止损'
                break
            if 方向 > 0 and b['收'] < df['低'].iloc[k - 窗口:k].min():
                平仓价 = df['开'].iloc[k + 1] if k + 1 < len(df) else b['收']
                原因 = '反向突破'
                break
            if 方向 < 0 and b['收'] > df['高'].iloc[k - 窗口:k].max():
                平仓价 = df['开'].iloc[k + 1] if k + 1 < len(df) else b['收']
                原因 = '反向突破'
                break
            k += 1

        if 平仓价 is None:
            平仓价, 原因, k = df['收'].iloc[-1], '数据结束', len(df) - 1

        毛利 = (平仓价 - 开仓价) * 方向 * 乘数 * 手数
        交易.append({
            '开仓时间': df['时间'].iloc[j], '方向': '多' if 方向 > 0 else '空',
            '开仓价': 开仓价, '止损价': 止损价, '止损宽度': atr,
            '平仓时间': df['时间'].iloc[k], '平仓价': 平仓价, '原因': 原因,
            '持仓根数': k - j + 1, '毛利': 毛利, '成本': 成本, '净利': 毛利 - 成本,
        })
        i = k + 1

    return pd.DataFrame(交易)


def 统计(t):
    if len(t) == 0:
        return {}
    赢 = t[t['净利'] > 0]
    亏 = t[t['净利'] <= 0]
    胜率 = len(赢) / len(t)
    平均盈 = 赢['净利'].mean() if len(赢) else 0.0
    平均亏 = 亏['净利'].mean() if len(亏) else 0.0
    累计 = np.cumsum(t['净利'].values)
    峰值 = np.maximum.accumulate(累计)
    return {
        '笔数': len(t), '胜率': 胜率, '平均盈': 平均盈, '平均亏': 平均亏,
        '盈亏比': (平均盈 / abs(平均亏)) if 平均亏 else float('inf'),
        '期望': 胜率 * 平均盈 + (1 - 胜率) * 平均亏,
        '总盈亏': t['净利'].sum(), '总成本': t['成本'].sum(),
        '平均毛利': t['毛利'].mean(),
        '最大回撤': float((累计 - 峰值).min()),
        '平均持仓根数': t['持仓根数'].mean(),
    }


