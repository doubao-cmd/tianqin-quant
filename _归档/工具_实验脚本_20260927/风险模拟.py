def 打印一():
    print("=" * 78)
    print("  【一】回撤的恢复成本 —— 亏掉多少，就要用多涨回来")
    print("=" * 78)
    print(f"  {'回撤':>8}{'回到原净值需要涨':>18}{'换算成 R 单位':>18}")
    print("-" * 78)
    for d in (0.05, 0.10, 0.20, 0.30, 0.40, 0.50, 0.70, 0.90):
        r = 恢复成本(d)
        print(f"  {d*100:>7.0f}%{r*100:>17.1f}%{r*100/1.0:>15.0f}%等效")
    print()
    print("  ⇒ 不对称是**乘性**的：亏 50% 要涨 100%，亏 90% 要涨 900%。")
    print("     所以风险管理的首要目标不是「赚更多」，而是「别让回撤变深」。")
    print()


def 打印二(p, b, f列表, 笔数, 连亏档=(5, 10, 15, 20)):
    亏率 = 1.0 - p
    print("=" * 78)
    print(f"  【二】连亏：会发生吗？发生后回撤多深？（胜率 {p:.0%} ⇒ 亏率 {亏率:.0%}）")
    print("=" * 78)
    print(f"  A. 跑 {笔数} 笔，出现「至少一次 N 连亏」的概率")
    print(f"  {'N 连亏':>8}{'单次连续概率':>16}{f'{笔数}笔内至少一次':>20}")
    print("-" * 78)
    for N in 连亏档:
        print(f"  {N:>8}{亏率**N:>16.4%}{至少一次连亏概率(亏率, 笔数, N):>19.1%}")
    print()
    print("  ⚠️ 单次概率看着极小，但「跑得够久」之后它几乎必然发生 ——")
    print("     这就是为什么风控要按「连亏会发生」来设计，而不是按「大概不会吧」。")
    print()
    print(f"  B. 连亏 N 笔后账户跌多少（复利口径：1-(1-f)^N）")
    头 = f"  {'单笔风险 f':>12}" + "".join(f"{f'{N}连亏':>12}" for N in 连亏档)
    print(头)
    print("-" * 78)
    for f in f列表:
        行 = f"  {f*100:>11.2f}%" + "".join(f"{连亏回撤(f, N)*100:>11.1f}%" for N in 连亏档)
        d10 = 连亏回撤(f, 10)
        if d10 >= 0.50:
            标 = "  ⚠️ 10 连亏就过半"
        elif d10 >= 0.30:
            标 = "  ⚠️ 10 连亏腰斩级"
        elif d10 >= 0.10:
            标 = "  ⚠️ 10 连亏两位数"
        else:
            标 = ""
        print(行 + 标)
    print()
    print("  ⚠️ 线性直觉是错的：f 翻 10 倍，回撤不是翻 10 倍，而是按 (1-(1-f)^N) 加速。")
    print()


def 打印三(p, b, f列表, 显示凯利):
    q = 1.0 - p
    算术期望 = p * b - q
    f凯 = 凯利(p, b)
    f零 = 零增长点(p, b)
    print("=" * 78)
    print(f"  【三】几何增长率 g(f) —— 真正决定账户长期命运的量（p={p:.0%}, b={b}）")
    print("=" * 78)
    print(f"  算术期望/笔 = p·b - q = {p:.2f}×{b} - {q:.2f} = {算术期望:+.3f} R  （>0，信号本身是赚的）")
    print(f"  凯利最优 f* = (p·b - q)/b = {f凯:.4%}")
    print(f"  g(f) 再次归零的 f  = {f零:.4%}" if f零 else "  g(f) 在合理范围内不归零")
    print()
    print(f"  {'刻度 f':>10}{'g(f)/笔':>12}{'1000笔后中位':>16}{'评价':>32}")
    print("-" * 78)
    候选 = list(f列表) + [0.0001, f凯, f凯 / 2.0, f凯 * 2.0]
    if f零:
        候选.append(f零 * 1.25)       # 越过临界点，看负增长区长什么样
    点 = sorted({round(x, 8) for x in 候选 if 0 < x < 1})
    f凯r = round(f凯, 8)
    for f in 点:
        g = 几何增长率(f, p, b)
        倍 = math.exp(g * 1000) if g * 1000 < 700 else float("inf")
        倍s = f"{倍:,.2f}×" if 倍 != float("inf") else "∞"
        if f零 and f >= f零:
            评 = "⚠️ 负增长区 —— 正期望也长期亏钱"
        elif f <= f凯r:
            评 = "增长区（f 越大越快）"
        else:
            评 = "收益递减区（越大越慢）"
        标 = "  ★凯利" if abs(f - f凯r) < 1e-9 else (
            "  ★我们 0.3%" if abs(f - 0.003) < 1e-9 else "")
        print(f"  {f:>10.4%}{g:>12.6f}{倍s:>16}{评:>32}{标}")
    print()
    print("  ⚠️ 「1000 笔后中位」= e^(g×1000)，是**中位数**不是平均数 ——")
    print("     真实分布的 5% 分位要低得多，见【四】。")
    print()
    if 显示凯利 and f凯 > 0:
        print(f"  对照：我们的 0.30% ÷ 凯利 {f凯:.2%} = 凯利的 {0.003/f凯*100:.1f}%（约 1/{f凯/0.003:.0f}）")
        print("        —— 极保守。理由：凯利假设 p/b 精确已知且恒定，现实里估错就爆。")
        print()
    print("  ⇒ 关键结论：**同一套正期望信号，把刻度调得太大，长期照样亏钱**。")
    print("     原因不是信号坏了，是你在大回撤里失去了继续下注的本金。")
    print()


def 钱(x):
    """把金额缩到万 / 亿，否则大数字会把表格挤爆。"""
    ax = abs(x)
    if ax >= 1e8:
        return f"{x/1e8:,.1f}亿"
    if ax >= 1e4:
        return f"{x/1e4:,.1f}万"
    return f"{x:,.0f}"


def 打印四(p, b, f列表, 笔数, 次数, 起始, 破产线):
    print("=" * 78)
    print(f"  【四】蒙特卡洛：{次数} 场 × 每场 {笔数} 笔，起始 {起始:,.0f}")
    print("=" * 78)
    print(f"  {'刻度 f':>9}{'中位结局':>12}{'5% 分位':>12}{'95% 分位':>12}"
          f"{'回撤中位':>10}{'腰斩率':>8}{'跑完还亏':>9}")
    print("-" * 78)
    for f in f列表:
        最终, 回撤s, 破产 = 蒙特卡洛(p, b, f, 笔数, 次数, 起始, 破产线)
        亏场 = sum(1 for v in 最终 if v < 起始) / len(最终)
        print(f"  {f*100:>8.2f}%{钱(分位(最终,0.5)):>12}{钱(分位(最终,0.05)):>12}"
              f"{钱(分位(最终,0.95)):>12}{分位(回撤s,0.5)*100:>9.1f}%"
              f"{破产/次数*100:>7.1f}%{亏场*100:>8.1f}%")
    print()
    print("  ⇒ 注意「5% 分位」这一列 —— 那是**最坏 5% 的世界的结局**，")
    print("     风控应该照这一列活，不是照中位数活。")
    print("  ⇒ 「跑完还亏」是**明明正期望、跑完 1000 笔却仍是亏的**场次占比：")
    print("     刻度小的时候它很低，刻度越过凯利点后它飙升 ——")
    print("     这不是运气差，是几何增长率已经转负（见【三】）。")
    print()


def main():
    ap = argparse.ArgumentParser(
        description="单笔风险刻度模拟：连亏、回撤、凯利与结局分布",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--p", type=float, default=0.40, help="胜率（默认 0.40）")
    ap.add_argument("--b", type=float, default=2.0, help="盈亏比（默认 2.0）")
    ap.add_argument("--n", type=int, default=1000, help="每场交易笔数（默认 1000）")
    ap.add_argument("--f", type=str, default="0.3,1,2,3,5",
                    help="要比较的刻度，%% 为单位，逗号分隔（默认 0.3,1,2,3,5）")
    ap.add_argument("--sim", type=int, default=2000, help="蒙特卡洛场数（0 = 跳过）")
    ap.add_argument("--equity", type=float, default=400000, help="起始权益（默认 400000）")
    ap.add_argument("--破产线", dest="ruin", type=float, default=0.5,
                    help="权益跌破起始的这个比例算破产（默认 0.5）")
    ap.add_argument("--kelly", action="store_true", help="附加凯利倍数对照")
    args = ap.parse_args()

    f列表 = [float(x) / 100.0 for x in args.f.split(",") if x.strip()]
    if not (0 < args.p < 1):
        raise SystemExit("--p 必须在 0 和 1 之间")
    if args.b <= 0:
        raise SystemExit("--b 必须为正")

    print()
    print(f"  参数：胜率 p={args.p:.2f} ｜ 盈亏比 b={args.b} ｜ 每场 {args.n} 笔 ｜ "
          f"刻度 f={','.join(f'{x*100:g}%' for x in f列表)}")
    print()

    打印一()
    打印二(args.p, args.b, f列表, args.n)
    打印三(args.p, args.b, f列表, args.kelly)
    if args.sim > 0:
        打印四(args.p, args.b, f列表, args.n, args.sim, args.equity, args.ruin)
    else:
        print("  （--sim 0：跳过蒙特卡洛）\n")

    print("=" * 78)
    print("  怎么用这个工具")
    print("=" * 78)
    print("  1. 先填 --p / --b —— 用你**实测**的胜率和盈亏比，不要用希望值。")
    print("  2. 看【二】B 表：找出「10 连亏时你还睡得着」的那个 f —— 那就是你的上限。")
    print("  3. 看【四】5% 分位：如果它让你难受，说明 f 还是太大。")
    print("  4. 记住前提：这些数字假设 p/b 恒定。真实策略会**漂移**，所以要再打折。")
    print()


if __name__ == "__main__":
    main()
