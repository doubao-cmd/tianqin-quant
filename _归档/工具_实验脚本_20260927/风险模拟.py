# -*- coding: utf-8 -*-
"""风险模拟 —— 单笔风险的「刻度」设多大，账户才活得下去（模块 5 · 第二课）

背景
----
第一课的风险等式：`总收益 = 目标风险额 × ΣR`，其中有一条推论说
「目标风险额只是刻度，改大改小只同倍放大收益与回撤，夏普不动」。

那句话成立有一个前提：**每笔风险额按固定基数算**（本项目引擎用
`RISK_EQUITY=400000` 写死，就是为此）。真实账户的权益是滚动的 ——
亏了钱，下一笔的风险额跟着变小；赚了钱，下一笔变大。于是「刻度」不再中性：

    同一个 ΣR（比如 +20 个单位），f=0.3% 时账户约 1.06 倍；
    f 调大到某个程度，账户**反而变少** —— 因为中途回撤太深，
    等信号终于开始赚的时候，能下注的本金已经没了。

本工具把这件事算成四块：
    【一】回撤的恢复成本（亏和赚的不对称性）
    【二】N 连亏：会发生吗？发生后回撤有多深？
    【三】几何增长率 vs 刻度 f（凯利点在哪、过了哪里变成负的）
    【四】蒙特卡洛：同一套信号，不同刻度下的结局分布

用法
----
    python 工具/风险模拟.py
    python 工具/风险模拟.py --p 0.4 --b 2.0 --n 1000 --f 0.3,1,2,3,5
    python 工具/风险模拟.py --sim 0            # 只出解析表（很快）
    python 工具/风险模拟.py --kelly            # 附加：与凯利倍数的对照

⚠️ `p`（胜率）和 `b`（盈亏比）是**这套信号的真实参数**，不是你能随便选的。
   不知道自己策略真相时，用保守假设，并把结论当「上界」看 ——
   真实世界的 p / b 会漂移，还会受跳空、滑点影响（实际亏损常常超过设定的风险额）。
"""

import argparse
import math
import random


# ---------------------------------------------------------------------------
# 解析部分
# ---------------------------------------------------------------------------

def 恢复成本(d):
    """回撤掉比例 d 之后，需要涨多少才能回到原来的净值。

    净值 1 → 1-d，要回到 1 需要乘 1/(1-d) ⇒ 涨幅 = d/(1-d)。
    亏 50% 要涨 100%，亏 90% 要涨 900% —— 这就是「亏容易、赚难」。
    """
    return d / (1.0 - d) if 0 <= d < 1 else float("inf")


def 连亏回撤(f, n):
    """单笔风险比例 f、连亏 n 笔后，账户从峰值跌掉多少（复利口径）。"""
    return 1.0 - (1.0 - f) ** n


def 至少一次连亏概率(亏率, 笔数, N):
    """n 笔交易里，出现「至少一次 N 连亏」的概率（Gusella 近似）。

    直觉：N 连亏在 n 笔里有 (n-N+1) 个可能起点，每个起点要连续亏 N 次
    （概率 亏率^N），末尾还得跟一次不亏，避免同一个长序列被重复计数。
    全是小概率，所以用泊松近似 1-exp(-期望次数)。
    """
    if 亏率 <= 0:
        return 0.0
    if 亏率 >= 1:
        return 1.0
    x = max(0, 笔数 - N + 1) * (1.0 - 亏率) * (亏率 ** N)
    return -math.expm1(-x)            # = 1 - e^{-x}，小数值下精度更好


def 几何增长率(f, p, b):
    """按「当前权益 × f」下注时，每笔的期望对数增长率 g(f)。

    g(f) = p·ln(1 + f·b) + (1-p)·ln(1 - f)
    长期账户 ≈ e^{g·n} —— 真正决定账户命运的是 g，不是算术期望。
    g > 0 才涨得起来；g = 0 是长期打平；g < 0 是**正期望信号也会亏钱**。
    """
    if f <= 0:
        return 0.0
    if f >= 1:
        return float("-inf")
    return p * math.log(1.0 + f * b) + (1.0 - p) * math.log(1.0 - f)


def 凯利(p, b):
    """凯利最优下注比例 f* = (p·b - q) / b —— 使 g(f) 最大的 f。

    ⚠️ 它是**理论上界**，不是目标：前提是 p、b 精确已知且永不漂移。
       实际做的是 1/4 凯利、1/10 凯利，理由见工具末尾的说明。
    """
    return (p * b - (1.0 - p)) / b


def 零增长点(p, b, 上限=0.95):
    """g(f) 再次穿过 0 的那个 f（超过它，长期必亏）。二分求解。"""
    lo = 凯利(p, b)
    if lo <= 0:
        return 0.0
    hi = 上限
    if 几何增长率(hi, p, b) > 0:
        return None                   # 到上限都还没转负
    for _ in range(200):
        mid = (lo + hi) / 2.0
        if 几何增长率(mid, p, b) > 0:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2.0


# ---------------------------------------------------------------------------
# 蒙特卡洛
# ---------------------------------------------------------------------------

def 分位(xs, q):
    s = sorted(xs)
    if not s:
        return float("nan")
    i = min(len(s) - 1, max(0, int(round(q * (len(s) - 1)))))
    return s[i]


def 蒙特卡洛(p, b, f, 笔数, 次数, 起始, 破产线, seed=42):
    """模拟 次数 场「笔数 笔交易」，返回 (最终权益列表, 最大回撤列表, 破产场数)。

    破产 = 权益跌破 起始×破产线（默认腰斩）。用中途 break 停止，避免负数权益。
    """
    rng = random.Random(seed)
    下限 = 起始 * 破产线
    最终, 回撤s, 破产 = [], [], 0
    for _ in range(次数):
        eq = 起始
        peak = eq
        mdd = 0.0
        死 = False
        for _ in range(笔数):
            风险额 = eq * f
            if rng.random() < p:
                eq += 风险额 * b
            else:
                eq -= 风险额
            if eq > peak:
                peak = eq
            dd = (peak - eq) / peak
            if dd > mdd:
                mdd = dd
            if eq < 下限:
                死 = True
                break
        最终.append(eq)
        回撤s.append(mdd)
        if 死:
            破产 += 1
    return 最终, 回撤s, 破产


