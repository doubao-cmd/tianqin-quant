def main():
    ap = argparse.ArgumentParser(add_help=True)
    ap.add_argument("--策略", default=None, help="只看某个策略（按账本「策略」字段匹配）")
    ap.add_argument("--K", type=int, default=None,
                    help="累计试验次数（默认 = Σ 各账本「累计试验次数」字段；缺字段的格退回版本数）")
    ap.add_argument("--明细", action="store_true", help="在【二】里也列出「无夏普 / 无指标」的版本行")
    args = ap.parse_args()

    账本s, 告警 = 读账本()
    if args.策略:
        账本s = [d for d in 账本s if d["_策略"] == args.策略]
        告警 = [a for a in 告警 if a[0] in [d["_文件"] for d in 账本s]]
        if not 账本s:
            print(f"没有策略 = {args.策略!r} 的账本")
            sys.exit(2)
    if not 账本s:
        print("工具/_账本/ 里没有账本文件")
        sys.exit(2)

    print("=" * 96)
    print("  回测体检：这份回测是真的，还是「跑得多」跑出来的")
    print("=" * 96)
    print(f"  读入账本 {len(账本s)} 份 ｜ 版本 {sum(len(d.get('版本',[])) for d in 账本s)} 个")

    K = 打印一(账本s, args.K, 告警)
    行s = 打印二(账本s, K, args.明细)
    打印三(账本s, K)
    打印四(行s)
    打印五(账本s, K, 行s)
    print()


if __name__ == "__main__":
    main()
