def 打印二(账本s, K, 明细):
    门槛 = 门槛t(K)
    行s = []
    来源计数 = {}
    不一致 = []
    for d in 账本s:
        版本级 = []
        起 = len(行s)
        for v in d.get("版本", []):
            区间, 来源 = 取区间(d, v)
            if 来源 == "版本" and 区间 not in 版本级:
                版本级.append(区间)
            Y = 年数(区间)
            来源计数[来源 or "无"] = 来源计数.get(来源 or "无", 0) + 1
            r = 版本行(v, K, Y)
            r["账本"] = d["_文件"]
            r["区间"] = 区间
            r["区间来源"] = 来源
            r["年数"] = Y
            行s.append(r)
        # 顶层「区间」只描述其中一个版本 ⇒ 可能与版本级区间矛盾。
        # 若某版本的年数与顶层年数差 2 倍以上，该版本的 t 值判读**对窗口选择敏感**，打 ⚠。
        顶层年 = 年数(d.get("区间"))
        if 版本级 and 顶层年:
            for r in 行s[起:]:
                if r["年数"] and (r["年数"] / 顶层年 > 2 or 顶层年 / r["年数"] > 2):
                    r["窗口敏感"] = True
            if any(r.get("窗口敏感") for r in 行s[起:]):
                不一致.append((d["_文件"], d.get("区间"), 顶层年,
                              {x: 年数(x) for x in 版本级}))

    print()
    print("=" * 96)
    print("  【二】逐版本体检：年化夏普 → t 值 → 比门槛")
    print("=" * 96)
    print(f"  门槛 t = {门槛:.2f}（K = {K}）")
    print()
    # 前置闸门：判决需要至少 30 笔观测（2026-09-25 新增，理由见本段末尾）
    笔数门槛 = 30
    print(f"  {'账本':<20}{'版本':<5}{'标记':<5}{'年数':>6}{'笔数':>6}{'年化夏普':>10}{'t':>8}  判定")
    print("-" * 96)
    有t = [r for r in 行s if r["t"] is not None]

    def 样本足(r):
        """观测数不足 ⇒ t 值的正态近似失效 ⇒ **只报数字、不下判决**。"""
        return r["笔"] is None or r["笔"] >= 笔数门槛

