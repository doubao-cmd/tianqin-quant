def 打印四(行s):
    print()
    print("=" * 96)
    print("  【四】成本体检：利润是赚来的，还是被成本吃掉的")
    print("=" * 96)
    有比 = [r for r in 行s if r["成本比"] is not None and r["初始"]]
    if not 有比:
        print("  没有可算成本占比的版本（缺「结束权益/初始资金/手续费」）。")
        return
    print(f"  {'账本':<20}{'版本':<5}{'净收益':>10}{'成本':>9}{'毛利':>9}{'占比':>8}{'元/单边':>9}  {'口径':<16}判定")
    print("-" * 96)
    超半 = []
    单价s = {}
    for r in sorted(有比, key=lambda x: -x["成本比"]):
        p = r["成本比"]
        毛利太小 = abs(r["毛利"]) < r["初始"] * 0.005      # 毛利 < 初始资金 0.5% ⇒ 比值无意义
        if 毛利太小:
            标 = "毛利≈0，占比无意义"
        elif p > 1.0:
            标 = "成本 > 毛利 ⇒ 净亏"
            超半.append(r)
        elif p > 0.5:
            标 = "过半，临界"
            超半.append(r)
        else:
            标 = ""
        单 = f"{r['元每单边']:.1f}" if r.get("元每单边") else "-"
        if r.get("元每单边"):
            单价s.setdefault(r["账本"], []).append((r["版本"], r["元每单边"]))
        print(f"  {r['账本']:<20}{str(r['版本']):<5}{r['净']:>10,.0f}{r['成本']:>9,.0f}"
              f"{r['毛利']:>9,.0f}{p*100:>7.1f}%{单:>9}  {str(r['成本口径']):<16}{标}")
    print("-" * 96)
    print(f"  ⇒ 成本占毛利 > 50% 的有 {len(超半)}/{len(有比)} 个版本。")
    负毛利 = [r for r in 行s
              if r["初始"] and r["净"] is not None and (r["净"] + (r["成本"] or 0)) <= 0]
    if 负毛利:
        print(f"  ⚠️ 另有 **{len(负毛利)} 个版本毛利本身 ≤ 0** —— 把成本整额加回去依然亏。它们算不出占比，")
        print("     但那本身就是结论：**这些版本不是「被成本吃掉」，是信号本身没有正期望。**")
        print(f"     ⇒ 有成本数据的版本共 {len(有比) + len(负毛利)} 个：毛利为正 {len(有比)} 个、毛利为负 {len(负毛利)} 个。")
    print()
    print("  ⚠️ 口径诚实说明：「手续费」口径**低估**真实成本（滑点藏在成交价里，不进手续费）；")
    print("     「成本(手续费+滑点)」才是全口径 —— 同一版本只会有一种，本工具优先取全口径。")
    print("  ⚠️ 毛利（= 净收益 + 成本）接近 0 时，这个比值可以任意大（见上「毛利≈0」标注），")
    print("     **不要拿它当结论** —— 那只是分母趋零，不是「成本特别高」。")
    print("  ⇒ **成本占毛利 > 50% 意味着：策略赚的钱里一半以上交给了市场。**")
    print("     这时「优化策略」不如「降低换手」—— 但降换手要改逻辑，不是改参数（规则 4）。")

    print()
    print("  ── 成本探针：用「元/单边」反查成本栏自不自洽 ──")
    print("     元/单边 = 总手续费 ÷ (开仓+平仓) 笔数。**手数是未知量**，所以它本身不是单价；")
    print("     但同一账本内两个版本若 元/单边 差得远，只可能是 ①手数变了 ②费率变了。")
    print("     判据不是「差异要小」，而是：**差异能不能被解释清楚**。说不清 ⇒ 这格别用来比成本。")
    漂 = []
    for 名, lst in 单价s.items():
        if len(lst) < 2:
            continue
        vals = [x[1] for x in lst]
        比 = max(vals) / min(vals)
        if 比 > 1.2:
            漂.append((名, min(vals), max(vals), 比))
    if not 漂:
        print("     本批账本内未发现 >20% 的单边成本漂移。")
    else:
        for 名, lo, hi, 比 in sorted(漂, key=lambda x: -x[3]):
            print(f"     · {名}：{lo:.1f} → {hi:.1f} 元/单边（{比:.2f} 倍）")
        print()
        print("     2026-09-25 逐条追过的两条（结论留档，别再重查）：")
        print("      ① PVC_双均线 那组主因是**手数**：v1 固定 1 手 → v7 手数 8 手。已用归档报告")
        print("         `_归档/历史报告/01_双均线/PVC/PVC_双均线_30min_out.txt` 逐笔核实：")
        print("         64 笔里 **60 笔恒为上限 8 手**（94%），仅 4 笔因 ATR 高企降到 5/6 手；")
        print("         按报告自述的 6.5 元/手·单边（1.5 手续费 + 5 滑点）算 502×6.5=3,263 元，")
        print("         与账本 3,327 元差 1.96% ⇒ 成本栏正常。（顺手又印证了 HAND_MAX=8 那个老 bug）")
        print("      ② 但 PVC 的**费率本身也在漂**：v1/v2 反推 1.00 元/手，v3~v5 是 1.42，v7 是 1.5")
        print("         —— 来自不同合约/日期的交易所费率表。**⇒ 该账本的成本栏跨版本不完全可比**，")
        print("         报「成本占毛利」前要先确认两边费率口径一致。其他 4 品种未发现同类漂移。")


