"""
==========================================================
 回测体检：这份回测是真的，还是「跑得多」跑出来的
==========================================================

用法：
    python 工具/回测体检.py                     # 体检全部账本
    python 工具/回测体检.py --策略 布林带        # 只看某个策略
    python 工具/回测体检.py --K 200             # 手动指定累计试验次数
    python 工具/回测体检.py --明细               # 每个版本都列出来

它回答的问题：
    账本里有 45 个落盘版本、每个都带着收益率和夏普。
    哪些是真的？——**先问一句「我为了这个数字试了多少次」。**

五段输出：
    【一】K 与门槛         —— 你为这些数字试了多少次，门槛 t 是多少
    【二】逐版本体检        —— 年化夏普 → t 值 → 比门槛（含 ⚠「窗口敏感」打标）
    【三】样本内 vs 样本外   —— 落差、缺「标记」的版本、以及「零落盘」版本的登记
    【四】成本体检         —— 成本占毛利 + 「元/单边」成本探针
    【五】宣判             —— 有 / 没有通过门槛的版本

★ K 从哪来（2026-09-25 起）：
    每个账本顶层有 `累计试验次数` 字段 = 该格「有凭证可查的尝试次数下界」
    （落盘版本 + 零落盘实验；口径写在 `试验次数口径` 里）。
    全局 K = Σ 各格字段值。字段缺失时退回该格的版本数，并打「无字段」标记。
    ⚠️ 它仍是下界 —— 2026-09-23 之前未逐次登记的实验无法追溯。
    字段的意义不是把 K 算准，而是**从此不必再事后重数**（见各账本「写法约定」）。

★ 顺手做的三项数据体检（**账本脏了，上面全是空算**）：
    ① 「品种 / 策略」字段 vs 文件名是否一致
    ② 版本级「区间」vs 顶层「区间」是否矛盾（顶层只描述其中一个版本）
    ③ 「元/单边」是否在同账本内漂移 —— 手数变了？还是费率变了？
    ④ 「无指标」版本是否都写明了原因（`落盘` 字段）；没写的才告警

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
★ 本工具最重要的一件事：把「夏普」和「门槛」摆到同一个量纲上
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

报告里的「夏普率」是 **年化** 口径（tqsdk 基于日权益序列）。
而 `研究路线图.md` 7.6 的门槛 √(2·lnK/N) 里的 N 是**观测数**。
⇒ 拿年化夏普去比 per-trade 门槛，是**两个不同量纲的数字**，
   「刚好卡在门槛上」这种巧合没有任何统计含义。

统一办法：两边都化成 **t 值**（t 值无量纲，跨样本长度、跨品种可比）。

    t ≈ 年化夏普 × √年数          （等价于 per-trade 夏普 × √笔数）
    门槛 t = √(2 · ln K)          （Bonferroni / White Reality Check 量级）

    ★ 为什么这个折算可靠：设年化因子为 P（每年 P 个观测），则
        SR_年化 = SR_单期 × √P，而观测数 N = 年数 × P
        ⇒ t = SR_单期 × √N = (SR_年化/√P) × √(年数·P) = **SR_年化 × √年数**
      **P 被完全消掉了** —— 所以不管 tqsdk 按 250 天还是按 30 分钟 K 线年化，
      折算出的 t 都一样。这个恒等式是本工具敢下判断的依据。

    夏普 > +门槛 t  ⇒ 显著为正（可能是真 alpha）
    夏普 < −门槛 t  ⇒ **显著为负**（是真在亏钱，不是噪声；别指望换参数救）
    |t| < 门槛 t    ⇒ 与零无法区分（说「有/没有优势」都不成立）

⚠️ 门槛对 K 不敏感、对样本长度极敏感：
   K 从 112（账本登记）→ 300（2.7 倍），门槛 t 只从 3.07 → 3.38（+10%）；
   而半年样本的门槛 t 是 2.5 年样本的 √5 ≈ 2.24 倍。
   ⇒ **「样本太短」比「试得太多」致命得多。**

数据来源：`工具/_账本/*.json`（每个「策略×品种」的逐版本记录）。
"""

