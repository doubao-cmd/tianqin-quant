def 数(s):
    """把账本里的字符串指标转成 float。认 '2.09%' / '204,182' / '-0.40' / '60%'。
    认不出来（'-'、None、空串）返回 None —— 绝不猜。"""
    if s is None:
        return None
    if isinstance(s, (int, float)):
        return float(s)
    t = str(s).strip().replace(",", "").replace("%", "").replace("＋", "+").replace("−", "-")
    if not t or t in ("-", "--", "—", "N/A", "n/a"):
        return None
    try:
        return float(t)
    except ValueError:
        return None


def 年数(区间):
    """从 '2026-03-13 ~ 2026-09-13' 估出样本年数。认不出返回 None。"""
    if not 区间:
        return None
    import re
    m = re.findall(r"(\d{4})-(\d{1,2})-(\d{1,2})", str(区间))
    if len(m) < 2:
        return None
    try:
        a = date(int(m[0][0]), int(m[0][1]), int(m[0][2]))
        b = date(int(m[1][0]), int(m[1][1]), int(m[1][2]))
    except ValueError:
        return None
    d = (b - a).days
    return d / 365.25 if d > 0 else None


def 取区间(d, v=None):
    """取样本区间：**优先版本级，退回账本级**。返回 (区间, 来源)。

    ⚠️ 为什么不直接用账本顶层的「区间」：那个字段**只描述其中一个版本**。
       实测 `PVC_双均线.json` 顶层写的是 2025-03-13 ~ 2025-09-13（那是 v7 期末考的
       样本外区间），而 v1~v6 跑的是 2026-03-13 ~ 2026-09-13 —— 拿顶层区间给所有
       版本算年数，年份会算错（本例恰好两个窗口都是半年，侥幸没出事）。
    """
    if v is not None and v.get("区间"):
        return str(v["区间"]), "版本"
    if d.get("区间"):
        return str(d["区间"]), "账本"
    return None, None


def 门槛t(K):
    """Bonferroni 量级的多重检验门槛（t 值）。"""
    return math.sqrt(2.0 * math.log(max(K, 2)))


def 读账本():
    """读入全部账本。

    ★ 权威来源 = **文件名** `<品种>_<策略>.json`（`工具/汇总报告.py` 也按文件名定位）。
      内容里的 `品种`/`策略` 字段是人工写的，实测有 4 份写错（复制模板没改），
      所以本工具以文件名为准，同时把「字段与文件名矛盾」的账本报出来。
    """
    out = []
    告警 = []
    for p in sorted(glob.glob(os.path.join(_ROOT, "工具", "_账本", "*.json"))):
        名 = os.path.basename(p)[:-5]
        try:
            d = json.load(open(p, encoding="utf-8"))
        except Exception as e:
            print(f"  ⚠️ 读不了 {名}：{e}")
            continue
        d["_文件"] = 名
        # 文件名解析：第一个下划线前是品种，之后是策略
        品种名, _, 策略名 = 名.partition("_")
        d["_品种"] = 品种名
        d["_策略"] = 策略名
        # 与内容字段对账
        错 = []
        if d.get("品种") and d.get("品种") != 品种名:
            错.append(f"品种 字段={d.get('品种')!r} ≠ 文件名={品种名!r}")
        if d.get("策略") and d.get("策略") != 策略名:
            错.append(f"策略 字段={d.get('策略')!r} ≠ 文件名={策略名!r}")
        if 错:
            告警.append((名, 错))
        out.append(d)
    return out, 告警


def 成本占比(m):
    """成本 / 毛利。优先用「总成本(手续费+滑点)」，退而用「总手续费」。
    ⚠️ 手续费口径会**低估**（滑点藏在成交价里，不计入手续费）。
    ⚠️ 毛利（= 净收益 + 成本）接近 0 时这个比值**没有意义**（可以任意大），
       所以一并把毛利和初始资金返回，交给调用方判断要不要显示。
    """
    净 = None
    初始 = m.get("初始资金")
    if m.get("结束权益") is not None and 初始 is not None:
        净 = m["结束权益"] - 初始
    成本 = m.get("总成本(手续费+滑点)")
    口径 = "成本(手续费+滑点)"
    if 成本 is None:
        成本 = m.get("总手续费")
        口径 = "手续费(低估)"
    if 成本 is None or 净 is None:
        return None, None, None, 初始, 净
    毛利 = 净 + 成本
    if 毛利 <= 0:
        return None, 口径, 毛利, 初始, 净
    return 成本 / 毛利, 口径, 毛利, 初始, 净


def 版本行(v, K, Y):
    """把一个版本算成体检行。"""
    m = {}
    for k, val in (v.get("指标") or {}).items():
        m[k] = 数(val)
    收益 = m.get("收益率")
    年化 = m.get("年化收益")
    夏普 = m.get("夏普率")          # ★ 年化口径
    回撤 = m.get("最大回撤")
    笔 = m.get("开仓次数")
    成本比, 成本口径, 毛利, 初始, 净 = 成本占比(m)

    t = None
    if 夏普 is not None and Y:
        t = 夏普 * math.sqrt(Y)

    # 元/单边 = 总手续费 ÷ (开仓+平仓) 笔数。★ 手数是未知的，所以它**不是单价**；
    # 但它是「成本探针」：同一账本内两版本若 元/单边 差很多，只可能是手数变了或费率变了。
    单边笔数 = None
    if m.get("开仓次数"):
        单边笔数 = (m["开仓次数"] + m["平仓次数"]) if m.get("平仓次数") else m["开仓次数"] * 2
    元每单边 = (m["总手续费"] / 单边笔数) if (m.get("总手续费") and 单边笔数) else None

    return {
        "版本": v.get("版本"),
        "标记": v.get("标记"),
        "标题": (v.get("标题") or "").strip(),
        "日期": v.get("日期"),
        "收益": 收益,
        "年化": 年化,
        "夏普": 夏普,
        "回撤": 回撤,
        "笔": 笔,
        "开": m.get("开仓次数"),
        "平": m.get("平仓次数"),
        "t": t,
        "成本比": 成本比,
        "成本口径": 成本口径,
        "毛利": 毛利,
        "初始": 初始,
        "净": 净,
        "元每单边": 元每单边,
        "窗口敏感": False,
        "成本": (m.get("总成本(手续费+滑点)") if m.get("总成本(手续费+滑点)") is not None
                 else m.get("总手续费")),
    }


