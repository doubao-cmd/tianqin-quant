def 判数据(周期, 段起, 段止):
    """返回 (结论, 有效起, 有效年数, 说明)

    结论 ∈ 覆盖 / 部分缺 / 全缺
    「有效起」= max(段起, 数据边界) —— 段内**真正有数据**的那一段起点。
    ⚠️ 「部分缺」不等于不可用，而是**样本比段定稿更短** ⇒ 门槛对应的夏普更高。
    """
    起 = 主连起点.get(归一周期(周期))
    if not 起:
        return ('未知', 段起, 0.0, '（无该周期的边界记录）')

    def _年(a, b):
        import datetime
        d = (datetime.date(*map(int, b.split('-'))) - datetime.date(*map(int, a.split('-')))).days
        return round(d / 365.25, 2)

    if 段起 >= 起:
        return ('覆盖', 段起, _年(段起, 段止), '起点 %s ≥ 数据边界 %s' % (段起, 起))
    if 段止 < 起:
        return ('全缺', 起, 0.0, '段止 %s < 数据边界 %s ⇒ 整段无数据' % (段止, 起))
    return ('部分缺', 起, _年(起, 段止),
            '段起 %s < 数据边界 %s ⇒ 前段无数据，有效窗口缩到 %s' % (段起, 起, 起))



def 归一周期(s):
    s = (s or '').strip()
    if s in ('1d', 'day', '日线', '86400'):
        return '1d'
    if s in ('30min', '30m', '1800', '半小时'):
        return '30min'
    return s


def 重叠(a起, a止, b起, b止):
    return not (a止 < b起 or b止 < a起)


def 判污染(周期, 品种, 段起, 段止):
    """返回 (严重度, [命中的事件])；严重度取最重：重 > 中 > 轻 > 干净"""
    p = 归一周期(周期)
    hits = []
    for e in 污染事件:
        if e['周期'] != p:
            continue
        if e['品种'] is not None and 品种 not in e['品种']:
            continue
        if 重叠(段起, 段止, e['起'], e['止']):
            hits.append(e)
    级 = {'重': 3, '中': 2, '轻': 1}
    最重 = '干净'
    for e in hits:
        if 级[e['严重度']] > 级.get(最重, 0):
            最重 = e['严重度']
    return 最重, hits


def 可用性(严重度):
    if 严重度 == '干净':
        return '✅ 可用'
    if 严重度 == '轻':
        return '🟡 可用（读过收益、未据以调参；明记风险）'
    if 严重度 == '中':
        return '🟠 谨慎（跑过期末考/筛选，非开发用；新策略尽量避开）'
    return '⛔ 不可用（做过开发或择优）'


