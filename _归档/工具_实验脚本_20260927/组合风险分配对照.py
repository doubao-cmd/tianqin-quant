def 判据(结果):
    """按预注册 Q1~Q3 自动判定（Q4 是纪律，无法自动判）。

    ⚠️★ Q1 于 2026-09-27 **跑完之后**被认定为**预注册写错**，此处已改正：
       原写法 `|净利 − 已实现净利| ≤ 1 元` —— 回源码（`lib/portfolio.py:271/458`）后看清：
         · `净利`       = 期末权益 − 初始资金；权益取的是 **TqSim `Account.balance`**
         · `已实现净利` = 已实现毛利 − 总成本（只算**已平仓**）
         ⇒ 两者之差**按构造就是期末浮动盈亏**，只在「期末无持仓」时为 0
         ⇒ 原判据等价于「要求评估期末必须空仓」，**不是容器正确性判据**。
       （与 2026-09-26 组合体检 P3 同一类错误：**判据对象设错**。）

    改正后拆成两条：
      Q1a **恒等式（硬闸门，必须精确）**：`已实现毛利 − 总成本 = 已实现净利`
      Q1b **量级闸门**：`|净利 − 已实现净利| ≤ Σ|期末净手数| × 保证金 × 3`
          （期末浮盈不可能超过持仓名义价值的量级；用来挡「数量级错误」，
            不是精确对账 —— 精确对账需要 TqSim 的 `float_profit` 与成交时间戳，
            两者当前都没落盘，见 Q1b 说明。）
    """
    甲乙 = list(结果.items())
    if len(甲乙) < 2:
        return []
    (a标, a), (b标, b) = 甲乙[0], 甲乙[1]
    am, bm = a["指标"], b["指标"]
    出 = []

    # Q1a 恒等式（硬闸门）
    ok1a = True
    for 标, r in 甲乙:
        m = r["指标"]
        差 = abs(m["已实现毛利"] - m["总成本"] - m["已实现净利"])
        if 差 > 1.0:
            ok1a = False
            出.append(("Q1a", False, "%s 恒等式差 %.3f 元 > 1（毛利−成本 ≠ 已实现净利）"
                       % (标[:12], 差)))
    if ok1a:
        出.append(("Q1a", True, "两档 `已实现毛利 − 总成本 = 已实现净利` 精确成立（差 ≤1 元）"))

    # Q1b 期末浮盈量级闸门
    ok1b = True
    for 标, r in 甲乙:
        m = r["指标"]
        残 = abs(m["净利"] - m["已实现净利"])
        上限 = 0.0
        明细 = []
        for k, v in r.get("每腿", {}).items():
            n = abs(float(v.get("净手数") or 0))
            if n < 1e-9:
                continue
            try:
                保证金 = float(PF._读品种池(k).get("保证金", 0) or 0)
            except Exception:
                保证金 = 0.0
            上限 += n * 保证金 * 3.0
            明细.append("%s %g 手" % (k, n))
        if 残 > 上限 and 上限 > 0:
            ok1b = False
            出.append(("Q1b", False, "%s 期末浮盈残差 %.2f > 量级上限 %.2f（持仓 %s）"
                       % (标[:12], 残, 上限, "、".join(明细))))
        elif 上限 == 0 and 残 > 1.0:
            ok1b = False
            出.append(("Q1b", False, "%s 期末**空仓**，但残差 %.2f ≠ 0 ⇒ 需查" % (标[:12], 残)))
        else:
            出.append(("Q1b", True, "%s 残差（期末浮盈）%.2f ≤ 量级上限 %.2f%s" % (
                标[:12], 残, 上限,
                ("（持仓 " + "、".join(明细) + "）") if 明细 else "（期末空仓）")))
    if not ok1b:
        出.append(("Q1b", False,
                   "⚠️ 未闭合：精确对账需要 TqSim 的 `float_profit` 与**成交时间戳**"
                   "（当前都未落盘）⇒ 只能用「净手数 × (期末价 − 均价) × 乘数」独立复算，"
                   "而该复算结果与残差**量级不符**（见 `_Q1对账复核.md`）"
                   "⇒ 本项**标记为未闭合**，不以「通过」结案。"))

    # Q2 封顶生效
    n拒 = bm.get("拒绝次数", 0)
    n腿 = bm.get("腿数最大", 0)
    if n拒 > 0 and n腿 <= 封顶K:
        出.append(("Q2", True, "B 档闸门拒绝 %d 次、腿数最大 %d ≤ K=%d ⇒ 封顶生效"
                   % (n拒, n腿, 封顶K)))
    else:
        出.append(("Q2", False,
                   "B 档拒绝 %d 次、腿数最大 %d ⇒ 封顶几乎未触发（9 品种天然少超 %d 腿）"
                   % (n拒, n腿, 封顶K)))

    # Q3 风险更可控
    # ⚠️ 回撤是**负数**（如 -15.75%）⇒ 必须比绝对值：-11.2% 比 -15.75% **更好**，
    #    直接写 db <= da 会得出相反的结论。
    va, vb = am.get("年化波动"), bm.get("年化波动")
    da, db = am.get("最大回撤", 0), bm.get("最大回撤", 0)
    if va is not None and vb is not None and vb < va and abs(db) <= abs(da):
        出.append(("Q3", True, "波动 %.2f%% → %.2f%%，回撤 %.2f%% → %.2f%%（均改善）"
                   % (va, vb, da, db)))
    else:
        出.append(("Q3", False, "波动 %s → %s，回撤 %.2f%% → %.2f%%（未同时改善）"
                   % (va, vb, da, db)))
    return 出


