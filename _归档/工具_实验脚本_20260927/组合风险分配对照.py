def 钱(x):
    """千分位金额 —— 只能用 .format（`%` 格式化不认 `,` 标志）。"""
    try:
        return "{:+,.0f}".format(float(x))
    except Exception:
        return str(x)


def 摘要(标签, r):
    m = r["指标"]
    print("\n  【%s】" % 标签)
    print("    每腿预算 %s%% ｜ 组合总预算上限 %s ｜ 腿数上限 %s" % (
        m.get("每腿预算%", "?"),
        ("%g%%" % m["组合总预算上限%"]) if m.get("组合总预算上限%") else "不限（漂移）",
        m.get("腿数上限") if m.get("腿数上限") else "不限"))
    print("    年化 %+.2f%% ｜ 夏普 %s ｜ 最大回撤 %.2f%% ｜ 年化波动 %s%%" % (
        m.get("年化收益", 0),
        ("%.3f" % m["夏普"]) if "夏普" in m else "n/a",
        m.get("最大回撤", 0),
        ("%.2f" % m["年化波动"]) if "年化波动" in m else "n/a"))
    print("    净利 %s ｜ 毛利 %s ｜ 成本 %s ｜ 成交 %d 手 / %d 笔" % (
        钱(m.get("净利", 0)), 钱(m.get("已实现毛利", 0)), 钱(m.get("总成本", 0)),
        m.get("成交手数", 0), m.get("成交笔数", 0)))
    print("    腿数 均值 %.2f ｜ 最大 %d ｜ 空仓日 %.1f%% ｜ 闸门拒绝 %d 次" % (
        m.get("腿数均值", 0), m.get("腿数最大", 0),
        m.get("零腿占比", 0), m.get("拒绝次数", 0)))
    分布 = m.get("腿数分布", {})
    tot = sum(分布.values()) or 1
    # 键做 int() 容错：json 落盘再读回来时，dict 的 int 键会变成字符串
    # （JSON 对象键只能是字符串）⇒ 不加固的话 `%d` 会抛
    #   TypeError: %d format: a real number is required, not str
    print("    腿数分布：" + " ｜ ".join(
        "%d腿 %.1f%%" % (int(k), v * 100.0 / tot)
        for k, v in sorted(分布.items(), key=lambda kv: int(kv[0]))))


