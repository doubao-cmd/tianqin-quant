        print("跑：%s" % 标签)
        print("  品种 %s ｜ 日线 ｜ %s ~ %s（评估自 %s）｜ 初始资金 %s" % (
            " / ".join(品种池), 区间[0], 区间[1], 评估起, f"{初始资金:,}"))
        print("=" * 78, flush=True)
        t0 = time.time()
        r = PF.跑组合(品种池, 区间[0], 区间[1], eval_start=评估起,
                      init_balance=初始资金, kline_sec=周期, 参数=P,
                      腿数上限=覆盖["腿数上限"], slip_ticks=1)
        print("  用时 %.1f 分钟" % ((time.time() - t0) / 60.0))
        摘要(标签, r)
        结果[标签] = r
        _存中间(结果)          # ★ 每档即存，不等到最后
