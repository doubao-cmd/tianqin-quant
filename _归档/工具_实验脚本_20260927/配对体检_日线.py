def 读品种池():
    """读 品种池/*.py，返回 key -> (主连, 中文名, 乘数, 一跳, 成本)。"""
    出 = {}
    目录 = os.path.join(ROOT, "品种池")
    if not os.path.isdir(目录):
        return 出
    for fn in sorted(os.listdir(目录)):
        if not fn.endswith(".py") or fn.startswith("_"):
            continue
        p = os.path.join(目录, fn)
        try:
            空 = {}
            src = io.open(p, encoding="utf-8").read()
            exec(compile(src, p, "exec"), 空)
            d = 空.get("品种") or {}
            k = d.get("key")
            if not k:
                continue
            出[k] = (d.get("主连"), d.get("中文名", k),
                    float(d.get("乘数", 0) or 0), float(d.get("一跳", 1) or 1),
                    float(d.get("成本", 0) or 0))
        except Exception:
            continue
    return 出


