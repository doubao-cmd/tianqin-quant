def 拉日线(syms, 详细=False):
    """拉主连日线，落盘缓存。**主线程串行、单会话**（禁并发，见项目铁律）。

    返回 {key: [(日期, close), ...]}（升序、只保留区间内）。
    """
    import datetime as _dt
    import time as _time

    sys.path.insert(0, ROOT)
    import config_account
    from tqsdk import TqApi, TqAuth

    u, p = config_account.check()
    api = TqApi(auth=TqAuth(u, p), web_gui=False)
    出 = {}
    行 = []
    try:
        for sym in syms:
            主连, 名, *_ = 品种表[sym]
            t0 = _time.time()
            try:
                ks = api.get_kline_serial(主连, 86400, data_length=日线根数)
                d = ks[ks["datetime"] > 0]
            except Exception as e:
                print("  x %-4s %s" % (sym, str(e)[:60]), flush=True)
                continue
            if len(d) == 0:
                print("  x %-4s 空数据（不写盘）" % sym, flush=True)
                continue
            序 = []
            for _, r in d.iterrows():
                ts = int(r["datetime"])
                if ts <= 0:
                    continue
                ds = _dt.datetime.fromtimestamp(ts / 1e9).strftime("%Y-%m-%d")
                if 区间[0] <= ds <= 区间[1]:
                    cl = float(r["close"])
                    if cl == cl and cl > 0:
                        序.append((ds, cl, float(r.get("volume", 0) or 0)))
            if not 序:
                print("  x %-4s 区间内无有效数据，跳过" % sym, flush=True)
                continue
            出[sym] = [(a, b) for a, b, _ in 序]
            for ds, cl, vo in 序:
                行.append({"key": sym, "日期": ds, "close": cl, "volume": vo})
            if 详细:
                print("  v %-4s %-6s %5d 根  %s ~ %s  (%.1fs)" % (
                    sym, 名, len(序), 序[0][0], 序[-1][0], _time.time() - t0),
                    flush=True)
    finally:
        try:
            api.close()
        except Exception:
            pass

    # ★ 空数据禁写盘：只有拉到东西才落缓存
    if 行:
        os.makedirs(os.path.dirname(缓存), exist_ok=True)
        with io.open(缓存, "w", encoding="utf-8", newline="") as f:
            w = csv.DictWriter(f, fieldnames=["key", "日期", "close", "volume"])
            w.writeheader()
            for r in 行:
                w.writerow(r)
    return 出


