def 拉真实残差(keys):
    """拉指数合约日线 ⇒ 池化「去均值」日收益残差（保留肥尾与自相关）。"""
    import pandas as pd

    def 读品种(key):
        import importlib.util as ilu
        p = os.path.join(ROOT, "品种池", f"{key}.py")
        spec = ilu.spec_from_file_location(f"_sp_{key}", p)
        m = ilu.module_from_spec(spec)
        spec.loader.exec_module(m)
        return m.品种

    import config_account
    from tqsdk import TqApi, TqAuth

    USER, PWD = config_account.check()
    api = TqApi(auth=TqAuth(USER, PWD), web_gui=False)
    各 = []
    try:
        for k in keys:
            p = 读品种(k)
            sym = p["主连"].replace("KQ.m@", "KQ.i@")
            ks = api.get_kline_serial(sym, 86400, data_length=4000)
            上次 = -1
            t0 = time.time()
            while time.time() - t0 < 45:
                try:
                    api.wait_update(deadline=time.time() + 6)
                except Exception:
                    break
                现在 = int((ks["datetime"] > 0).sum())
                if 现在 > 0 and 现在 == 上次:
                    break
                上次 = 现在
            d = ks[ks["datetime"] > 0].copy()
            d["日期"] = pd.to_datetime(d["datetime"] / 1e9, unit="s", utc=True) \
                          .dt.tz_convert("Asia/Shanghai").dt.tz_localize(None)
            d = d.set_index("日期")
            d = d[~d.index.duplicated(keep="last")]
            r = d["close"].astype(float).pct_change().dropna()
            r = r - r.mean()          # 去均值 ⇒ 零均值残差池（H0 基准）
            各.append(r.values)
            print("  [%s] %-9s %d 根残差  std %.3f%%"
                  % (k, p["中文名"], len(r), float(r.std(ddof=1)) * 100))
    finally:
        api.close()
    return np.concatenate(各)


def 功效_bootstrap(池, SR, T, c=门槛, M=None, 种子_=None):
    """有放回重采样真实残差 + 注入 μ_d。保留肥尾（对功效的影响与正态不同）。"""
    M = M or 模拟次数
    rng = np.random.default_rng(种子 if 种子_ is None else 种子_)
    mu = SR / math.sqrt(每年交易日)
    n = len(池)
    命中正 = 命中负 = 0
    done = 0
    while done < M:
        m = min(批大小, M - done)
        idx = rng.integers(0, n, size=(m, T))
        x = mu + 池[idx]
        s = x.std(axis=1, ddof=1)
        t = x.mean(axis=1) / (s / math.sqrt(T))
        命中正 += int((t > c).sum())
        命中负 += int((t < -c).sum())
        done += m
    return 命中正 / M, 命中负 / M


