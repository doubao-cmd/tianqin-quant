# 核心：蒙特卡洛功效
# ============================================================
def 功效(SR, T, c=门槛, M=None, 种子_=None):
    """模拟 `P(|t| > c)` —— 真实年化夏普 = SR、样本 T 根时的**检出概率**。

    返回 (正侧, 负侧)：
        正侧 = P(t > c)   —— 认出「有优势」（成功）
        负侧 = P(t < −c)  —— **把真优势误判成显著亏损**（也是失败，且更要命）
    日收益标准差归一为 1（不影响 t，因为 t 无量纲）；μ_d = SR/√250 使其年化夏普 = SR。
    """
    M = M or 模拟次数
    种子_ = 种子 if 种子_ is None else 种子_
    rng = np.random.default_rng(种子_)
    mu = SR / math.sqrt(每年交易日)
    命中正 = 命中负 = 0
    done = 0
    while done < M:
        m = min(批大小, M - done)
        x = mu + rng.standard_normal((m, T))
        s = x.std(axis=1, ddof=1)
        t = x.mean(axis=1) / (s / math.sqrt(T))
        命中正 += int((t > c).sum())
        命中负 += int((t < -c).sum())
        done += m
    return 命中正 / M, 命中负 / M


def 正态尾(z):
    """P(Z > z)。"""
    return 0.5 * math.erfc(z / math.sqrt(2.0))


def 功效理论(SR, T, c=门槛):
    """正态近似（λ 远大于 1 时与蒙特卡洛一致，用于交叉验证）。"""
    lam = SR * math.sqrt(T / 每年交易日)
    return 正态尾(c - lam) + 正态尾(c + lam)


def 反解SR(T, c=门槛, 目标=0.80, M=None):
    """二分找「功效 = 目标」对应的年化夏普 —— 即**最小可测夏普 MDES**。"""
    M = M or 模拟次数
    lo, hi = 0.0, 20.0
    for _ in range(26):
        mid = (lo + hi) / 2.0
        p, _ = 功效(mid, T, c, M)
        if p < 目标:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2.0


def 有效腿数(n, rho):
    """等权组合的有效独立腿数 = n / (1 + (n−1)ρ)。

    推导：n 个品种、各期收益 (μ, σ²)、两两相关 ρ ⇒ 等权组合
        组合夏普 = 单腿夏普 × √(n / (1 + (n−1)ρ))
    ⇒ **组合真正的价值 = 放大 √n_eff**，等价于把样本长度乘 n_eff 倍。
    """
    return n / (1.0 + (n - 1.0) * rho)


