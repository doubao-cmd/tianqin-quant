def _钱(x):
    """千分位金额。

    ⚠️ Python 的 `%` 格式化**不支持** `,` 标志 —— 在 `%` 和 `.0f` 中间插一个
    千分位逗号会抛 `ValueError: unsupported format character ','`。
    千分位只有 `str.format` / f-string 才认。2026-09-26 首次体检跑了 26 分钟、
    数字全算出来了，却倒在这个打印语句上，报告也没写出来 ⇒ 现在统一走本函数。
    """
    try:
        return "{:+,.0f}".format(float(x))
    except Exception:
        return str(x)


def _可存(r):
    """挑出能安全 json 化的部分（DataFrame 一律不存 —— 太大且没必要）。"""
    out = {}
    for k, v in r.items():
        if hasattr(v, "columns"):          # pandas DataFrame
            continue
        out[k] = v
    return out


def _摘要(tag, r):
    m = r["指标"]
    print("\n  【%s】" % tag)
    print("    年化 %+.2f%% ｜ 夏普 %s ｜ t %s ｜ 最大回撤 %.2f%% ｜ 年化波动 %s%%" % (
        m.get("年化收益", 0),
        ("%.3f" % m["夏普"]) if "夏普" in m else "n/a",
        ("%.3f" % m["t"]) if "t" in m else "n/a",
        m.get("最大回撤", 0),
        ("%.2f" % m["年化波动"]) if "年化波动" in m else "n/a"))
    print("    净利 %s 元 ｜ 已实现毛利 %s ｜ 总成本 %s ｜ 成交 %d 手 / %d 笔" % (
        _钱(m.get("净利", 0)), _钱(m.get("已实现毛利", 0)), _钱(m.get("总成本", 0)),
        m.get("成交手数", 0), m.get("成交笔数", 0)))
    print("    腿数 均值 %.2f ｜ 最大 %d ｜ 空仓日占比 %.1f%% ｜ 闸门拒绝 %d 次" % (
        m.get("腿数均值", 0), m.get("腿数最大", 0),
        m.get("零腿占比", 0), m.get("拒绝次数", 0)))
    分布 = m.get("腿数分布", {})
    tot = sum(分布.values()) or 1
    print("    腿数分布：" + " ｜ ".join(
        "%d腿 %.1f%%" % (k, v * 100.0 / tot) for k, v in sorted(分布.items())))


def 跑体检(K=None, 快=False):
    Kv = K or 腿数默认
    列表 = [("不限腿数", None)] if 快 else [("不限腿数", None), ("K=%d" % Kv, Kv)]

    结果 = {}
    for 标签, Kv in 列表:
        print("\n" + "=" * 78)
        print("跑组合：%s（%d 品种 ｜ 日线 ｜ %s ~ %s）" % (
            标签, len(品种池), 评估起, 区间[1]))
        print("=" * 78)
        r = PF.跑组合(
            品种池, 区间[0], 区间[1], eval_start=评估起,
            init_balance=初始资金, kline_sec=周期, 参数=参数,
            腿数上限=Kv, slip_ticks=1)
        结果[标签] = r
        _摘要(标签, r)
    return 结果


