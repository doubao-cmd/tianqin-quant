def 跑体检(K=None, 快=False):
    Kv = K or 腿数默认
    列表 = [("不限腿数", None)]
    # ★ K = 品种数时「不限」与「K=N」**完全等价**（品种数就是天然上限）
    #   ⇒ 不重复跑第二遍。2026-09-26 实测：两档各 45 分钟，第二档纯属白等。
    if not 快 and Kv < len(品种池):
        列表.append(("K=%d" % Kv, Kv))
    elif not 快:
        print("\n  [跳过第二档] K=%d = 品种数 %d ⇒ 与「不限腿数」等价，不重复跑。"
              % (Kv, len(品种池)))

    结果 = {}
    for 标签, Kv in 列表:
        print("\n" + "=" * 78)
        print("跑组合：%s（%d 品种 ｜ 日线 ｜ %s ~ %s）" % (
            标签, len(品种池), 评估起, 区间[1]))
        print("=" * 78)
        r = PF.跑组合(
            品种池, 区间[0], 区间[1], eval_start=评估起,
            init_balance=初始资金, kline_sec=周期, 参数=参数,
            腿数上限=Kv, slip_ticks=1)
        结果[标签] = r
        _摘要(标签, r)
    return 结果


