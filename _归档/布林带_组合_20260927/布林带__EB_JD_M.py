def _钱(x):
    """千分位金额。

    ⚠️ Python 的 `%` 格式化**不支持** `,` 标志 —— 在 `%` 和 `.0f` 中间插一个
    千分位逗号会抛 `ValueError: unsupported format character ','`。
    千分位只有 `str.format` / f-string 才认（2026-09-26 血的教训）。
    """
    try:
        return "{:+,.0f}".format(float(x))
    except Exception:
        return str(x)


def _可存(r):
    """挑出能安全 json 化的部分（DataFrame 一律不存 —— 太大且没必要）。"""
    out = {}
    for k, v in r.items():
        if hasattr(v, "columns"):
            continue
        out[k] = v
    return out


def _摘要(tag, r):
    m = r["指标"]
