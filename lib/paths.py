# -*- coding: utf-8 -*-
"""
顶层目录名集中定义（唯一的「目录叫什么」出处）
==========================================================
项目里所有"目录名"字符串都从这里取，避免散落各处、改名时漏改。

分工：
  · 本文件        -> 顶层目录名（回测结果 / 实测记录 / ...）与根目录定位
  · strategy_dirs -> 策略编号目录名（01_双均线 / 02_均线排列 / ...）

纯标准库、零依赖，engine.py 与 工具/*.py 都可放心导入。
"""
import os

# ---------------- 根目录定位 ----------------
# 从本文件所在目录（<根>/lib）向上找到含 lib 的那一层，即项目根。
# 换电脑、换盘符、改项目文件夹名字都不会失效（不写死任何绝对路径）。
_HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(_HERE)


def 根(*parts):
    """拼出项目内的绝对路径：根("回测结果", "01_双均线", "PVC")"""
    return os.path.join(ROOT, *parts)


# ---------------- 顶层目录名 ----------------
回测结果 = "回测结果"      # 回测报告（html + 成交明细 txt）
实测记录 = "实测记录"      # 模拟盘台账 / 流水 / 心跳
回测记录 = "回测记录"      # 回测结果条目的结构化 JSON（汇总页数据源）
运行日志 = "运行日志"      # bat / 脚本的运行日志
策略 = "策略"              # 旧结构：五策略编号目录（2026-09-27 已从归档搬回根目录）
策略池 = "策略池"          # 新结构：策略纯逻辑（与品种、参数分离）
品种池 = "品种池"          # 新结构：品种合约信息
组合 = "组合"              # 新结构：策略 × 品种 × 参数 的绑定
工具 = "工具"              # 工具脚本
归档 = "_归档"             # 归档（不参与日常运行）
待迁移 = "_待迁移"         # 迁移期临时区


def 回测目录(策略目录, 品种):
    """回测结果/<策略目录>/<品种>/  —— 自动建好，返回路径。"""
    p = 根(回测结果, 策略目录, 品种)
    os.makedirs(p, exist_ok=True)
    return p


def 实测目录(策略目录, 品种):
    """实测记录/<策略目录>/<品种>/  —— 自动建好，返回路径。"""
    p = 根(实测记录, 策略目录, 品种)
    os.makedirs(p, exist_ok=True)
    return p
